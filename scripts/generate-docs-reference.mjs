#!/usr/bin/env node

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const rootDir = resolve(scriptDir, "..");
const cliPath = resolve(rootDir, "dist/cli/index.js");
const defaultOutputPath = resolve(rootDir, "docs/orca-reference.md");

const outputArgIndex = process.argv.indexOf("--out");
const outputPath =
  outputArgIndex >= 0 && process.argv[outputArgIndex + 1]
    ? resolve(rootDir, process.argv[outputArgIndex + 1])
    : defaultOutputPath;

if (!existsSync(cliPath)) {
  console.error("Missing dist/cli/index.js. Run `npm run build` before generating docs.");
  process.exit(1);
}

const packageJson = JSON.parse(readFileSync(resolve(rootDir, "package.json"), "utf8"));
const typeSource = readFileSync(resolve(rootDir, "src/types/index.ts"), "utf8");
const effortSource = readFileSync(resolve(rootDir, "src/types/effort.ts"), "utf8");

function runHelp(args) {
  return execFileSync(process.execPath, [cliPath, ...args, "--help"], {
    cwd: rootDir,
    encoding: "utf8",
    env: { ...process.env, NO_COLOR: "1" },
  }).trimEnd();
}

function extractSourceSection(source, startMarker, endMarker) {
  const startIndex = source.indexOf(startMarker);
  if (startIndex < 0) {
    throw new Error(`Could not find source marker: ${startMarker}`);
  }

  const endIndex = source.indexOf(endMarker, startIndex);
  if (endIndex < 0) {
    throw new Error(`Could not find source marker: ${endMarker}`);
  }

  return source.slice(startIndex, endIndex).trim();
}

function extractArrayValues(source, marker) {
  const match = source.match(new RegExp(`${marker} = \\[([^\\]]+)\\] as const;`));
  if (!match?.[1]) {
    throw new Error(`Could not find values for ${marker}`);
  }

  return [...match[1].matchAll(/"([^"]+)"/g)].map((item) => item[1]);
}

const commandHelps = [
  ["orca", []],
  ["orca run", ["run"]],
  ["orca plan", ["plan"]],
  ["orca status", ["status"]],
  ["orca list", ["list"]],
  ["orca skills", ["skills"]],
  ["orca resume", ["resume"]],
  ["orca cancel", ["cancel"]],
  ["orca answer", ["answer"]],
  ["orca pr", ["pr"]],
  ["orca pr draft", ["pr", "draft"]],
  ["orca pr create", ["pr", "create"]],
  ["orca pr publish", ["pr", "publish"]],
  ["orca pr status", ["pr", "status"]],
  ["orca setup", ["setup"]],
  ["orca help", ["help"]],
  ["orca pr-finalize", ["pr-finalize"]],
];

const configReference = extractSourceSection(
  typeSource,
  "export type PlannerAgent",
  "export function defineOrcaConfig",
);
const effortValues = extractArrayValues(effortSource, "CODEX_THINKING_LEVEL_VALUES");

const commandSections = commandHelps
  .map(([title, args]) => {
    const help = runHelp(args);

    return `### ${title}

\`\`\`text
${help}
\`\`\``;
  })
  .join("\n\n");

const markdown = `# orca

Coordinated agent run harness.

> Generated by \`node scripts/generate-docs-reference.mjs\` from \`orcastrator@${packageJson.version}\`. Do not edit this file by hand.

## Install

\`\`\`shell
npm install -g orcastrator
\`\`\`

## Command Reference

This section is generated from the Commander command tree used by the built Orca CLI.

${commandSections}

## Config Schema And Public Type Reference

Codex effort values: \`${effortValues.join("|")}\`.

This section is generated from the Zod-backed config schema and public types in \`src/types/index.ts\`, which are re-exported by the package entry point.

\`\`\`ts
${configReference}
\`\`\`
`;

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, markdown, "utf8");
console.log(`Wrote ${outputPath}`);
